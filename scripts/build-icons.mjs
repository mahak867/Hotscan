// Builds the inline icon sprite in index.html from Phosphor Icons (MIT).
// Run `npm run icons` after adding a name below. The app references icons as
// <svg class="ic"><use href="#i-NAME"/></svg>; nothing is fetched at runtime.
import fs from 'node:fs'

const DIR = 'node_modules/@phosphor-icons/core/assets'
// id → [phosphor name, weight]
const ICONS = {
  scan: ['scan', 'bold'], garage: ['garage', 'regular'], 'garage-f': ['garage', 'fill'],
  market: ['shopping-bag', 'regular'], 'market-f': ['shopping-bag', 'fill'],
  trend: ['chart-line-up', 'regular'], 'trend-f': ['chart-line-up', 'fill'],
  more: ['squares-four', 'regular'], 'more-f': ['squares-four', 'fill'],
  user: ['user', 'regular'], camera: ['camera', 'regular'], image: ['image', 'regular'], images: ['images-square', 'regular'],
  search: ['magnifying-glass', 'regular'], tag: ['tag', 'regular'], shield: ['shield-check', 'regular'],
  heart: ['heart', 'regular'], plus: ['plus', 'bold'], bell: ['bell', 'regular'], share: ['share-network', 'regular'],
  rupee: ['currency-inr', 'regular'], refresh: ['arrows-clockwise', 'regular'], chevron: ['caret-right', 'bold'], x: ['x', 'bold'],
  list: ['list-bullets', 'regular'], grid: ['squares-four', 'regular'], download: ['download-simple', 'regular'],
  book: ['book-open', 'regular'], target: ['crosshair', 'regular'], key: ['key', 'regular'],
  chat: ['whatsapp-logo', 'regular'], doc: ['file-text', 'regular'], trash: ['trash', 'regular'],
  store: ['storefront', 'regular'], flame: ['flame', 'regular'], calendar: ['calendar-blank', 'regular'],
  car: ['car-profile', 'light'], barcode: ['barcode', 'regular'], seal: ['seal-check', 'regular'],
}

const symbols = Object.entries(ICONS).map(([id, [name, weight]]) => {
  const file = `${DIR}/${weight}/${name}${weight === 'regular' ? '' : '-' + weight}.svg`
  const inner = fs.readFileSync(file, 'utf8').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  return `    <symbol id="i-${id}" viewBox="0 0 256 256">${inner}</symbol>`
}).join('\n')

const sprite = `<!-- icons:start (generated by scripts/build-icons.mjs — do not edit by hand) -->
<svg class="sprite" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">
  <defs>
${symbols}
  </defs>
</svg>
<!-- icons:end -->`

let html = fs.readFileSync('index.html', 'utf8')
const a = html.indexOf('<!-- icons:start'), b = html.indexOf('<!-- icons:end -->')
if (a < 0 || b < 0) throw new Error('icon markers not found in index.html')
fs.writeFileSync('index.html', html.slice(0, a) + sprite + html.slice(b + '<!-- icons:end -->'.length))
console.log('wrote', Object.keys(ICONS).length, 'icons')
